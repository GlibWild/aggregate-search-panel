export function StatusDot({ tone }: { tone: SessionTone }) {
  return <span className={`status-dot tone-${tone}`} aria-hidden="true" />;
}

export function Chip({
  children,
  active = false,
  onClick,
  title,
  tone,
}: {
  children: ReactNode;
  active?: boolean;
  onClick?: () => void;
  title?: string;
  tone?: 'accent' | 'muted' | 'danger';
}) {
  const className = ['chip', active ? 'is-active' : '', tone ? `chip-${tone}` : ''].join(' ').trim();
  if (!onClick) {
    return (
      <span className={className} title={title}>
        {children}
      </span>
    );
  }
  return (
    <button type="button" className={className} onClick={onClick} title={title}>
      {children}
    </button>
  );
}

export function Switch({
  checked,
  onChange,
  label,
  description,
  disabled,
}: {
  checked: boolean;
  onChange: (next: boolean) => void;
  label: string;
  description?: string;
  disabled?: boolean;
}) {
  return (
    <label className={`switch-row ${disabled ? 'is-disabled' : ''}`}>
      <span className="switch-text">
        <span className="switch-label">{label}</span>
        {description ? <span className="switch-desc">{description}</span> : null}
      </span>
      <input
        type="checkbox"
        className="switch-input"
        checked={checked}
        disabled={disabled}
        onChange={(event) => onChange(event.target.checked)}
      />
      <span className="switch-track" aria-hidden="true">
        <span className="switch-thumb" />
      </span>
    </label>
  );
}

export function Field({
  label,
  hint,
  required,
  children,
}: {
  label: string;
  hint?: string;
  required?: boolean;
  children: ReactNode;
}) {
  return (
    <label className="field">
      <span className="field-label">
        {label}
        {required ? <em>*</em> : null}
      </span>
      {children}
      {hint ? <span className="field-hint">{hint}</span> : null}
    </label>
  );
}

export function Modal({
  title,
  subtitle,
  onClose,
  children,
  footer,
  wide,
}: {
  title: string;
  subtitle?: string;
  onClose: () => void;
  children: ReactNode;
  footer?: ReactNode;
  wide?: boolean;
}) {
  return (
    <div className="modal-backdrop" role="dialog" aria-modal="true" aria-label={title}>
      <div className={`modal ${wide ? 'modal-wide' : ''}`}>
        <header className="modal-header">
          <div>
            <h2>{title}</h2>
            {subtitle ? <p>{subtitle}</p> : null}
          </div>
          <button type="button" className="icon-btn" onClick={onClose} title="关闭">
            <Icon name="close" />
          </button>
        </header>
        <div className="modal-body">{children}</div>
        {footer ? <footer className="modal-footer">{footer}</footer> : null}
      </div>
    </div>
  );
}

export function Toast({
  level,
  message,
}: {
  level: 'info' | 'success' | 'warn' | 'error';
  message: string;
}) {
  return (
    <div className={`toast toast-${level}`} role="status">
      <Icon name={level === 'error' || level === 'warn' ? 'alert' : 'check'} size={16} />
      <span>{message}</span>
    </div>
  );
}

